"""Create the intake schema and load class_dataset.csv into Postgres."""

import csv
import re
from pathlib import Path

import psycopg2

ROOT = Path(__file__).resolve().parent

SKILLS = (
    "programming",
    "data_stats",
    "frontend_design",
    "business_pitch",
)

SKILL_COLUMNS = {
    "programming": "skill_programming",
    "data_stats": "skill_data_stats",
    "frontend_design": "skill_frontend_design",
    "business_pitch": "skill_business_pitch",
}

SLOTS = (
    ("Weekday mornings", "weekday", "morning"),
    ("Weekday afternoons", "weekday", "afternoon"),
    ("Weekday evenings", "weekday", "evening"),
    ("Weekend mornings", "weekend", "morning"),
    ("Weekend afternoons", "weekend", "afternoon"),
    ("Weekend evenings", "weekend", "evening"),
)

COUNT_ORDER = (
    "skill",
    "tool",
    "availability_slot",
    "student",
    "student_skill",
    "student_tool",
    "student_availability",
)

DDL = """
DROP TABLE IF EXISTS
    student_availability,
    student_tool,
    student_skill,
    student,
    availability_slot,
    tool,
    skill
CASCADE;

CREATE TABLE skill (
    skill_id SMALLINT PRIMARY KEY,
    code TEXT NOT NULL UNIQUE
);

CREATE TABLE tool (
    tool_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE availability_slot (
    slot_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label TEXT NOT NULL UNIQUE,
    day_group TEXT NOT NULL CHECK (day_group IN ('weekday', 'weekend')),
    period TEXT NOT NULL CHECK (period IN ('morning', 'afternoon', 'evening')),
    UNIQUE (day_group, period)
);

CREATE TABLE student (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submitted_id TEXT NOT NULL UNIQUE,
    id_kind TEXT NOT NULL CHECK (id_kind IN ('netid', 'n_number', 'email')),
    full_name TEXT NOT NULL,
    school_year TEXT NOT NULL CHECK (
        school_year IN ('First-year', 'Sophomore', 'Junior', 'Senior')
    ),
    intro_programming TEXT NOT NULL CHECK (
        intro_programming IN ('took_it', 'equivalent', 'neither')
    ),
    working_style TEXT,
    interests TEXT NOT NULL,
    semester_goal TEXT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE student_skill (
    student_id INTEGER NOT NULL REFERENCES student (student_id),
    skill_id SMALLINT NOT NULL REFERENCES skill (skill_id),
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    PRIMARY KEY (student_id, skill_id)
);

CREATE TABLE student_tool (
    student_id INTEGER NOT NULL REFERENCES student (student_id),
    tool_id SMALLINT NOT NULL REFERENCES tool (tool_id),
    PRIMARY KEY (student_id, tool_id)
);

CREATE TABLE student_availability (
    student_id INTEGER NOT NULL REFERENCES student (student_id),
    slot_id SMALLINT NOT NULL REFERENCES availability_slot (slot_id),
    PRIMARY KEY (student_id, slot_id)
);
"""


def load_database_url(env_path: Path) -> str:
    for line in env_path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("DATABASE_URL="):
            return line.split("=", 1)[1].strip().strip('"').strip("'")
        if line.startswith(("postgres://", "postgresql://")):
            return line.strip('"').strip("'")
    raise SystemExit(f"DATABASE_URL not found in {env_path}")


def csv_path() -> Path:
    preferred = ROOT / "data" / "class_dataset.csv"
    fallback = ROOT / "class_dataset.csv"
    if preferred.is_file():
        return preferred
    if fallback.is_file():
        return fallback
    raise SystemExit(f"CSV not found at {preferred}")


def classify_id(submitted_id: str) -> str:
    if "@" in submitted_id:
        return "email"
    if re.fullmatch(r"N\d+", submitted_id):
        return "n_number"
    return "netid"


def split_semicolon(value: str) -> list[str]:
    return [part.strip() for part in value.split(";") if part.strip()]


def clean_working_style(value: str) -> str | None:
    text = value.strip()
    if text in ("", "#NAME?"):
        return None
    return text


def main() -> None:
    database_url = load_database_url(ROOT / ".env")
    source = csv_path()
    with source.open(newline="") as handle:
        rows = list(csv.DictReader(handle))

    connection = psycopg2.connect(database_url)
    try:
        with connection:
            with connection.cursor() as cursor:
                cursor.execute(DDL)

                for skill_id, code in enumerate(SKILLS, start=1):
                    cursor.execute(
                        "INSERT INTO skill (skill_id, code) VALUES (%s, %s)",
                        (skill_id, code),
                    )

                for label, day_group, period in SLOTS:
                    cursor.execute(
                        """
                        INSERT INTO availability_slot (label, day_group, period)
                        VALUES (%s, %s, %s)
                        """,
                        (label, day_group, period),
                    )

                cursor.execute("SELECT slot_id, label FROM availability_slot")
                slot_ids = {label: slot_id for slot_id, label in cursor.fetchall()}
                skill_ids = {code: skill_id for skill_id, code in enumerate(SKILLS, start=1)}
                tool_ids: dict[str, int] = {}

                def tool_id_for(name: str) -> int:
                    if name not in tool_ids:
                        cursor.execute(
                            "INSERT INTO tool (name) VALUES (%s) RETURNING tool_id",
                            (name,),
                        )
                        tool_ids[name] = cursor.fetchone()[0]
                    return tool_ids[name]

                for row in rows:
                    submitted_id = row["netid"].strip()
                    cursor.execute(
                        """
                        INSERT INTO student (
                            submitted_id, id_kind, full_name, school_year,
                            intro_programming, working_style, interests,
                            semester_goal, submitted_at
                        )
                        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
                        RETURNING student_id
                        """,
                        (
                            submitted_id,
                            classify_id(submitted_id),
                            row["name"].strip(),
                            row["school_year"].strip(),
                            row["intro_programming"].strip(),
                            clean_working_style(row["working_style"]),
                            row["interests"].strip(),
                            row["semester_goal"].strip(),
                            row["submitted_at"].strip(),
                        ),
                    )
                    student_id = cursor.fetchone()[0]

                    for code, column in SKILL_COLUMNS.items():
                        cursor.execute(
                            """
                            INSERT INTO student_skill (student_id, skill_id, rating)
                            VALUES (%s, %s, %s)
                            """,
                            (student_id, skill_ids[code], int(row[column])),
                        )

                    for name in split_semicolon(row["tools"]):
                        cursor.execute(
                            """
                            INSERT INTO student_tool (student_id, tool_id)
                            VALUES (%s, %s)
                            """,
                            (student_id, tool_id_for(name)),
                        )

                    for label in split_semicolon(row["availability"]):
                        slot_id = slot_ids.get(label)
                        if slot_id is None:
                            raise SystemExit(f"Unknown availability value: {label!r}")
                        cursor.execute(
                            """
                            INSERT INTO student_availability (student_id, slot_id)
                            VALUES (%s, %s)
                            """,
                            (student_id, slot_id),
                        )

                print(f"Loaded {source}")
                for table in COUNT_ORDER:
                    cursor.execute(f"SELECT COUNT(*) FROM {table}")
                    print(f"{table}: {cursor.fetchone()[0]}")
    finally:
        connection.close()


if __name__ == "__main__":
    main()
